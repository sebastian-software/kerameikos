#!/usr/bin/env python3
"""Writes the family theme from the tokens in DESIGN.md.

DESIGN.md's front matter is the one source of the palette. This script turns it into:

  theme/theme.css    custom properties (--kr-*), light and dark, the font face, the lockup
  theme/ardo.js      the Ardo theme every product site passes to <ArdoRoot theme={...}>
  theme/ardo.d.ts    its type
  theme/tokens.json  the same tokens for any other tool

Run it after changing a color in DESIGN.md:

  python3 tools/build-theme.py           # write the files
  python3 tools/build-theme.py --check   # fail if the files are out of date (CI)

It needs only Python's standard library.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "theme"

# The tokens of DESIGN.md as Ardo names them. Rules and code borders reuse the hairline.
ARDO = {
    "brand": "accent",
    "brandDark": "accent-2",
    "brandSubtle": "accent-wash",
    "brandInk": "on-accent",
    "accent": "accent",
    "ring": "accent",
    "bg": "paper",
    "bgSoft": "parchment",
    "bgMute": "mist",
    "text": "ink",
    "textLight": "ink-2",
    "textLighter": "ink-3",
    "border": "hair",
    "borderLight": "hair-2",
    "divider": "hair",
    "codeBg": "listing",
    "codeBorder": "hair",
}
# The shell takes its surfaces from the page ground, so header and sidebar never form boxes.
ARDO_SURFACES = {
    "headerBg": "var(--ardo-color-bg)",
    "sidebarBg": "var(--ardo-color-bg)",
    "sidebarRailBg": "var(--ardo-color-bgSoft)",
}
DISPLAY = '"Cinzel Hellenic", "Times New Roman", serif'
MARK_COLORS = ("mark-navy", "mark-bronze", "mark-paper")


def front_matter() -> dict:
    """The color maps of DESIGN.md's front matter. A small reader, enough for its flat maps."""
    text = (ROOT / "DESIGN.md").read_text()
    head = text.split("---", 2)[1]
    maps: dict = {}
    current = None
    for line in head.splitlines():
        top = re.match(r"^([a-z-]+):\s*$", line)
        if top:
            current = maps.setdefault(top.group(1), {})
            continue
        entry = re.match(r'^  ([a-z0-9-]+):\s*"(#[0-9a-f]{6})"\s*$', line)
        if entry and current is not None:
            current[entry.group(1)] = entry.group(2)
        elif not line.startswith(" "):
            current = None
    return {"light": maps["colors"], "dark": maps["colors-dark"]}


def css(tokens: dict) -> str:
    light, dark = tokens["light"], tokens["dark"]
    page = [name for name in light if name not in MARK_COLORS]

    def block(colors: dict, names: list, indent: str = "  ") -> str:
        return "\n".join(f"{indent}--kr-{name}: {colors[name]};" for name in names)

    return f"""/*
 * The Greek product family's theme: the palette of DESIGN.md as custom properties.
 * Generated by tools/build-theme.py from DESIGN.md; do not edit by hand.
 *
 * Light is the default. Dark follows the system unless the page sets light, and is forced by
 * class="dark" (as Ardo sets it) or data-theme="dark" on the root element.
 * The mark colors stay the same in both: the marks are never recolored.
 */

@font-face {{
  font-family: "Cinzel Hellenic";
  src: url("../CinzelHellenic-Regular.woff2") format("woff2");
  font-weight: 400;
  font-style: normal;
  font-display: swap;
}}

:root {{
{block(light, page)}
{block(light, list(MARK_COLORS))}
  --kr-display: {DISPLAY};
  --kr-body: system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;
  --kr-mono: ui-monospace, "SF Mono", Menlo, Consolas, monospace;
  color-scheme: light;
}}

@media (prefers-color-scheme: dark) {{
  :root:not(.light):not([data-theme="light"]) {{
{block(dark, page, "    ")}
    color-scheme: dark;
  }}
}}

:root.dark,
:root[data-theme="dark"] {{
{block(dark, page)}
  color-scheme: dark;
}}

/*
 * The lockup as live text: the small mark, then the name in Cinzel Hellenic capitals.
 *   <a class="kr-lockup" href="/"><img class="kr-lockup-mark" src=".../mark-small.svg" alt="">
 *   <span class="kr-lockup-name">Tereon</span></a>
 * Sizes follow DESIGN.md: name 0.625 and gap 0.35 of the mark's height (2rem in a header).
 */
.kr-lockup {{
  --kr-lockup-mark: 2rem;
  display: inline-flex;
  align-items: center;
  gap: calc(var(--kr-lockup-mark) * 0.35);
  color: var(--kr-ink);
  text-decoration: none;
}}
.kr-lockup-mark {{
  display: block;
  width: var(--kr-lockup-mark);
  height: var(--kr-lockup-mark);
}}
.kr-lockup-name {{
  font-family: var(--kr-display);
  font-size: calc(var(--kr-lockup-mark) * 0.625);
  font-weight: 400;
  letter-spacing: 0.16em;
  text-transform: uppercase;
  line-height: 1;
}}
"""


def ardo(tokens: dict) -> dict:
    def scheme(colors: dict) -> dict:
        return {"color": {**{k: colors[v] for k, v in ARDO.items()}, **ARDO_SURFACES}}

    return {
        "color": "amber",
        "accent": "amber",
        "neutral": "blue",
        "fonts": {"heading": DISPLAY},
        "light": scheme(tokens["light"]),
        "dark": scheme(tokens["dark"]),
    }


def ardo_js(tokens: dict) -> str:
    body = json.dumps(ardo(tokens), indent=2)
    return f"""// The Greek product family's Ardo theme. Generated by tools/build-theme.py from DESIGN.md;
// do not edit by hand.
//
//   import {{ KERAMEIKOS_ARDO_THEME }} from "kerameikos/ardo"
//   <ArdoRoot theme={{KERAMEIKOS_ARDO_THEME}} ...>
//
// The page ground carries header and sidebar, Cinzel Hellenic sets the headings, and the
// dark variant is the "night watch" of the Tereon homepage. Load the font with
// "kerameikos/theme.css" or the site's own @font-face.
export const KERAMEIKOS_ARDO_THEME = {body}
"""


ARDO_DTS = """// Generated by tools/build-theme.py; do not edit by hand.
import type { ArdoThemeProps } from "ardo/ui"

export declare const KERAMEIKOS_ARDO_THEME: ArdoThemeProps
"""


def outputs() -> dict:
    tokens = front_matter()
    return {
        "theme.css": css(tokens),
        "ardo.js": ardo_js(tokens),
        "ardo.d.ts": ARDO_DTS,
        "tokens.json": json.dumps(tokens, indent=2) + "\n",
    }


def main() -> None:
    check = "--check" in sys.argv[1:]
    stale = []
    for name, content in outputs().items():
        path = OUT / name
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        else:
            OUT.mkdir(exist_ok=True)
            path.write_text(content)
            print(f"wrote theme/{name}")
    if stale:
        sys.exit("out of date, run python3 tools/build-theme.py: " + ", ".join(stale))


if __name__ == "__main__":
    main()
